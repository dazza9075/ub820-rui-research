/* gen_subovl_font: host tool that bakes subovl's embedded fallback font (subovl_font.h) from a TTF.
 * Default source: Noto Sans Bold (SIL Open Font License 1.1, embedding in software is permitted).
 * Codepoints: ASCII 0x20-0x7E + Latin-1 0xA0-0xFF + a few typographic marks; 4 bits per pixel at EM px.
 * Build/run: cc -O2 gen_subovl_font.c -o gen_subovl_font -lm && ./gen_subovl_font /usr/share/fonts/google-noto/NotoSans-Bold.ttf > subovl_font.h */
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"
#include <stdio.h>
#include <stdlib.h>
#define EM 40
int main(int argc, char** argv){
    const char* path = argc > 1 ? argv[1] : "/usr/share/fonts/google-noto/NotoSans-Bold.ttf";
    FILE* f = fopen(path, "rb"); if(!f){ fprintf(stderr, "open %s\n", path); return 1; }
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    unsigned char* d = malloc(n); if(fread(d, 1, n, f) != (size_t)n) return 1; fclose(f);
    stbtt_fontinfo fi; if(!stbtt_InitFont(&fi, d, stbtt_GetFontOffsetForIndex(d, 0))){ fprintf(stderr, "init\n"); return 1; }
    float sc = stbtt_ScaleForMappingEmToPixels(&fi, EM);
    int asc, desc, gap; stbtt_GetFontVMetrics(&fi, &asc, &desc, &gap);
    int cps[300], ncp = 0;
    for(int c = 0x20; c <= 0x7E; c++) cps[ncp++] = c;
    for(int c = 0xA0; c <= 0xFF; c++) cps[ncp++] = c;
    int extra[] = { 0x152, 0x153, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x20AC, 0x266A, 0xFFFD };
    for(unsigned i = 0; i < sizeof extra / sizeof extra[0]; i++) if(stbtt_FindGlyphIndex(&fi, extra[i])) cps[ncp++] = extra[i];
    unsigned char* nib = calloc(1 << 22, 1); unsigned off = 0;
    printf("/* generated by gen_subovl_font.c from %s (SIL OFL 1.1) -- do not edit */\n", path);
    printf("#define SUBOVL_FONT_EM %d\n#define SUBOVL_FONT_ASC %.3ff\n#define SUBOVL_FONT_DESC %.3ff\n#define SUBOVL_FONT_N %d\n", EM, asc * sc, -desc * sc, ncp);
    printf("struct subovl_glyph { unsigned short cp; signed char x0, y0; unsigned char w, h; unsigned short adv4; unsigned off; };\n");
    printf("static const struct subovl_glyph subovl_font_g[%d] = {\n", ncp);
    for(int i = 0; i < ncp; i++){
        int g = stbtt_FindGlyphIndex(&fi, cps[i]); int adv, lsb; stbtt_GetGlyphHMetrics(&fi, g, &adv, &lsb);
        int w = 0, h = 0, x0 = 0, y0 = 0;
        unsigned char* bm = cps[i] == 0x20 || cps[i] == 0xA0 ? 0 : stbtt_GetGlyphBitmap(&fi, sc, sc, g, &w, &h, &x0, &y0);
        printf("{0x%04x,%d,%d,%d,%d,%d,%u},%s", cps[i], x0, y0, w, h, (int)(adv * sc * 4 + 0.5f), off, (i % 4 == 3) ? "\n" : "");
        for(int k = 0; k < w * h; k++){ unsigned v = (bm[k] + 8) / 17; if(v > 15) v = 15; unsigned idx = off + k;
            nib[idx >> 1] |= (idx & 1) ? v : (v << 4); }
        off += w * h; if(bm) stbtt_FreeBitmap(bm, 0);
    }
    printf("};\nstatic const unsigned char subovl_font_bits[%u] = {\n", (off + 1) / 2);
    for(unsigned i = 0; i < (off + 1) / 2; i++) printf("%d,%s", nib[i], (i % 32 == 31) ? "\n" : "");
    printf("};\n");
    return 0;
}
